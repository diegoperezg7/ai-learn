export type TKey = keyof (typeof dict)['es']
type Vars = Record<string, string | number>

export function translate(lang: Lang, key: TKey, vars?: Vars): string {
  let text: string = dict[lang][key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

/** Server notifications are stored in Spanish. Map the known templates when the UI is English. */
export function localizeNotification(lang: Lang, title: string, body: string): { title: string; body: string } {
  if (lang === 'es') return { title, body }
  const t = (key: TKey, vars?: Vars) => translate('en', key, vars)
  let match = title.match(/^Vence hoy: (.+)$/)
  if (match) {
    return {
      title: t('notif.dueToday', { title: match[1] }),
      body: body === 'Sin entregable definido.' ? t('notif.noDeliverable') : body,
    }
  }
  match = title.match(/^(\d+) tarea\(s\) atrasada\(s\)$/)
  if (match) return { title: t('notif.overdue', { n: match[1] }), body }
  match = title.match(/^Vas ([\d.]+) h por detras del ritmo$/)
  if (match) return { title: t('notif.behind', { hours: match[1] }), body: t('notif.behindBody') }
  match = title.match(/^Vas ([\d.]+) h por delante$/)
  if (match) return { title: t('notif.ahead', { hours: match[1] }), body: t('notif.aheadBody') }
  if (title === 'No has elegido el foco de hoy') return { title: t('notif.noFocus'), body: t('notif.noFocusBody') }
  match = title.match(/^Toca cerrar la review de (.+)$/)
  if (match) return { title: t('notif.reviewDue', { label: match[1] }), body: t('notif.reviewBody') }
  match = title.match(/^(\d+) dias seguidos$/)
  if (match) return { title: t('notif.streak', { n: match[1] }), body: t('notif.streakBody') }
  if (title === 'Llevas 7 dias sin descansar') return { title: t('notif.rest'), body: t('notif.restBody') }
  return { title, body }
}
